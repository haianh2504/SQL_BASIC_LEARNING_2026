-- Câu 1. In ra danh sách các sản phẩm (MASP,TENSP) do “Trung Quoc” sản xuất.
SELECT MASP, TENSP FROM SANPHAM WHERE NUOCSX = 'Trung Quoc';

-- Câu 2. In ra danh sách các sản phẩm (MASP, TENSP) có đơn vị tính là “cay”, ”quyen”.
SELECT MASP, TENSP FROM SANPHAM WHERE DVT IN ('cay', 'quyen');


-- Câu 3. In ra danh sách các sản phẩm (MASP,TENSP) có mã sản phẩm bắt đầu là “B” và kết thúc là “01”.
SELECT MASP, TENSP FROM SANPHAM WHERE MASP LIKE 'B%' AND MASP LIKE '%01';

-- Câu 4. In ra danh sách các sản phẩm (MASP,TENSP) do “Trung Quốc” sản xuất có giá từ 30.000 đến 40.000.
SELECT MASP, TENSP FROM SANPHAM WHERE NUOCSX = 'Trung Quoc' AND GIA BETWEEN 30000 AND 40000;

-- Câu 5. In ra danh sách các sản phẩm (MASP,TENSP) do “Trung Quoc” hoặc “Thai Lan” sản xuất có giá từ 30.000 đến 40.000.
SELECT MASP, TENSP FROM SANPHAM WHERE NUOCSX IN ('Trung Quoc', 'Thai Lan') AND GIA BETWEEN 30000 AND 40000;

-- Câu 6. In ra các số hóa đơn, trị giá hóa đơn bán ra trong ngày 1/1/2007 và ngày 2/1/2007.
SELECT SOHD, TRIGIA FROM HOADON WHERE NGHD IN ('20070101', '20070102');

-- Câu 7. In ra các số hóa đơn, trị giá hóa đơn trong tháng 1/2007, sắp xếp theo ngày (tăng dần) và trị giá của hóa đơn (giảm dần).
SELECT SOHD, TRIGIA FROM HOADON WHERE NGHD >= '20070101' AND NGHD < '20070101' ORDER BY NGHD ASC, TRIGIA DESC;

-- Câu 8. In ra danh sách các khách hàng (MAKH, HOTEN) đã mua hàng trong ngày 1/1/2007.
SELECT DISTINCT KHACHHANG.MAKH, HOTEN
FROM KHACHHANG
INNER JOIN HOADON
ON KHACHHANG.MAKH = HOADON.MAKH
WHERE NGHD = '20070101';

-- Câu 9. In ra số hóa đơn, trị giá các hóa đơn do nhân viên có tên “Nguyen Van B” lập trong ngày 28/10/2006.
SELECT SOHD, TRIGIA FROM HOADON
INNER JOIN NHANVIEN ON HOADON.MANV = NHANVIEN.MANV
WHERE HOTEN = 'Nguyen Van B' AND NGHD = '20061028';

-- Câu 10. In ra danh sách các sản phẩm (MASP,TENSP) được khách hàng có tên “Nguyen Van A” mua trong tháng 10/2006.
SELECT DISTINCT SANPHAM.MASP, TENSP FROM SANPHAM
INNER JOIN CTHD ON SANPHAM.MASP = CTHD.MASP
INNER JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
INNER JOIN KHACHHANG ON HOADON.MAKH = KHACHHANG.MAKH
WHERE HOTEN = 'Nguyen Van A' AND NGHD >= '20061001' AND NGHD < '20061101';

-- Câu 11. Tìm các số hóa đơn đã mua sản phẩm có mã số “BB01” hoặc “BB02”.
SELECT DISTINCT HOADON.SOHD FROM HOADON
INNER JOIN CTHD ON HOADON.SOHD = CTHD.SOHD
WHERE MASP IN ('BB01', 'BB02');

-- Câu 12. Tìm các số hóa đơn đã mua sản phẩm có mã số “BB01” hoặc “BB02”, mỗi sản phẩm mua với số lượng từ 10 đến 20.
SELECT DISTINCT HOADON.SOHD FROM HOADON
INNER JOIN CTHD ON HOADON.SOHD = CTHD.SOHD
WHERE MASP IN ('BB01','BB02') AND SL BETWEEN 10 AND 20;

-- Câu 13. Tìm các số hóa đơn mua cùng lúc 2 sản phẩm có mã số “BB01” và “BB02”, mỗi sản phẩm mua với số lượng từ 10 đến 20.
SELECT HOADON.SOHD FROM HOADON
INNER JOIN CTHD ON HOADON.SOHD = CTHD.SOHD
WHERE MASP IN ('BB01','BB02') AND SL BETWEEN 10 AND 20
GROUP BY HOADON.SOHD HAVING COUNT(DISTINCT MASP) = 2;


-- Câu 14. In ra danh sách các sản phẩm (MASP,TENSP) do “Trung Quoc” sản xuất hoặc các sản phẩm được bán ra trong ngày 1/1/2007.
SELECT SANPHAM.MASP, TENSP FROM SANPHAM
INNER JOIN CTHD ON SANPHAM.MASP = CTHD.MASP
INNER JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
WHERE SANPHAM.NUOCSX = 'Trung Quoc' OR HOADON.NGHD = '20070101';

-- Câu 15. In ra danh sách các sản phẩm (MASP,TENSP) không bán được.
SELECT SANPHAM.MASP, TENSP FROM SANPHAM 
LEFT OUTER JOIN CTHD ON SANPHAM.MASP = CTHD.MASP
WHERE CTHD.MASP IS NULL;

-- Câu 16. In ra danh sách các sản phẩm (MASP,TENSP) không bán được trong năm 2006.
SELECT SANPHAM.MASP, TENSP FROM SANPHAM 
WHERE NOT EXISTS(
    SELECT * FROM CTHD
    INNER JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
    WHERE SANPHAM.MASP = CTHD.MASP
    AND HOADON.NGHD >= '20060101' AND HOADON.NGHD < '20070101'
);

-- Câu 17. In ra danh sách các sản phẩm (MASP,TENSP) do “Trung Quoc” sản xuất không bán được trong năm 2006.
SELECT SANPHAM.MASP, TENSP FROM SANPHAM
WHERE NUOCSX = 'Trung Quoc' AND NOT EXISTS(
    SELECT * FROM SANPHAM
    INNER JOIN CTHD ON SANPHAM.MASP = CTHD.MASP
    INNER JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
    WHERE CTHD.MASP = SANPHAM.MASP AND NGHD < '20070101' AND NGHD >= '20060101'
);

-- Câu 18. Thống kê số lượng hóa đơn do mỗi nhân viên lập trong năm 2006, hiển thị (MANV, HOTEN, SoLuongHD).
SELECT NHANVIEN.MANV, HOTEN, COUNT(HOADON.SOHD) AS SoLuongHd FROM NHANVIEN
LEFT JOIN HOADON ON NHANVIEN.MANV = HOADON.MANV
WHERE NHANVIEN.MANV = HOADON.MANV
AND NGHD >= '20060101' AND NGHD < '20070101'
GROUP BY NHANVIEN.MANV, NHANVIEN.HOTEN;

-- Câu 19. In ra danh sách nhân viên và tổng số khách hàng khác nhau mà họ đã bán hàng cho trong năm 2006.
SELECT NHANVIEN.MANV, NHANVIEN.HOTEN, NHANVIEN.SODT, NHANVIEN.NGVL, COUNT(DISTINCT HOADON.MAKH) AS SoLuongKH FROM NHANVIEN
LEFT OUTER JOIN HOADON ON NHANVIEN.MANV = HOADON.MANV
AND NGHD >= '20060101' AND NGHD < '20070101'
GROUP BY NHANVIEN.MANV, NHANVIEN.HOTEN, NHANVIEN.SODT, NHANVIEN.NGVL;

-- Câu 20.Liệt kê sản phẩm (MASP, TENSP) có tổng số lượng bán ra nhiều nhất trong năm 2006.
SELECT TOP(1) WITH TIES SANPHAM.MASP, TENSP FROM SANPHAM
INNER JOIN CTHD ON SANPHAM.MASP = CTHD.MASP
LEFT OUTER JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
AND NGHD < '20070101' AND NGHD >= '20060101'
GROUP BY SANPHAM.MASP, TENSP ORDER BY SUM(CTHD.SL) DESC;

-- Câu 21. Tìm nhân viên có doanh số bán hàng cao nhất trong tháng 10/2006.
SELECT TOP(1) WITH TIES NV.MANV, NV.HOTEN, NV.SODT, NV.NGVL FROM NHANVIEN NV
INNER JOIN HOADON ON NV.MANV = HOADON.MANV
AND HOADON.NGHD >= '20061001' AND HOADON.NGHD < '20061101'
GROUP BY NV.MANV, NV.HOTEN, NV.SODT, NV.NGVL
ORDER BY SUM(HOADON.TRIGIA) DESC;

-- Câu 22. In ra danh sách sản phẩm không bán được trong năm 2007 nhưng có bán trong năm 2006.
SELECT DISTINCT SANPHAM.* FROM SANPHAM
INNER JOIN CTHD ON SANPHAM.MASP = CTHD.MASP
INNER JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
WHERE NGHD >= '20060101' AND NGHD < '20070101'
AND NOT EXISTS(
    SELECT * FROM CTHD
    INNER JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
    WHERE NGHD >= '20070101' AND NGHD < '20080101' AND SANPHAM.MASP = CTHD.MASP
);

-- Câu 23. Liệt kê danh sách sản phẩm (MASP, TENSP) được bán bởi ít nhất 2 nhân viên khác nhau.
SELECT SANPHAM.MASP, TENSP FROM SANPHAM
INNER JOIN CTHD ON SANPHAM.MASP = CTHD.MASP
INNER JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
GROUP BY SANPHAM.MASP, TENSP HAVING COUNT(DISTINCT HOADON.MANV) >= 2;

-- Câu 24. In ra danh sách khách hàng không mua sản phẩm nào do Thái Lan sản xuất.
SELECT DISTINCT KHACHHANG.* FROM KHACHHANG
WHERE NOT EXISTS(
    SELECT 1 FROM HOADON
    INNER JOIN CTHD ON HOADON.SOHD = CTHD.SOHD
    INNER JOIN SANPHAM ON CTHD.MASP = SANPHAM.MASP
    WHERE KHACHHANG.MAKH = HOADON.MAKH AND NUOCSX = 'Thai Lan'
);

-- Câu 25. Tìm hóa đơn có trị giá lớn nhất trong năm 2006, in ra (SOHD, NGHD, TRIGIA)
SELECT TOP(1) WITH TIES SOHD, NGHD, TRIGIA FROM HOADON
WHERE NGHD >= '20060101' AND NGHD < '20070101'
ORDER BY TRIGIA DESC;